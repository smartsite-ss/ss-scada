import {
  StorageAdapter,
  DataPoint,
  QueryOptions,
  WriteResult,
  AdapterCapabilities,
} from '../interfaces/storage-adapter.interface';

/**
 * Structured type for Nest Logger: sub-packages under pnpm may resolve to different @nestjs/common instances
 * (different peer dependency sets → nominal types are incompatible, TS2416); use a structural declaration to avoid this.
 */
interface MinimalLogger {
  log(message: any, ...optionalParams: any[]): void;
  error(message: any, ...optionalParams: any[]): void;
  warn(message: any, ...optionalParams: any[]): void;
  debug(message: any, ...optionalParams: any[]): void;
}

const BATCH_SIZE = 1000;
const FLUSH_INTERVAL = 5000;
const MAX_RETRIES = 3;
const RETRY_INTERVAL = 10000;
// CODE-05: per-fetch timeout (ms), preventing an indefinitely hung request from blocking the event loop
const FETCH_TIMEOUT_MS = 5000;

interface BufferedWrite {
  points: DataPoint[];
  attempts: number;
}

/** Read request descriptor: generated by each engine adapter hook; the base class performs the HTTP transport uniformly */
export interface EngineReadRequest {
  url: string;
  headers: Record<string, string>;
  body: string;
}

/**
 * Line Protocol engine adapter base class (shared by InfluxDB 2 / InfluxDB 3 Core / TDengine).
 *
 * Engineering skeleton extracted from InfluxdbAdapterService:
 * - In-memory buffering (1000 points / 5s) with batch writes;
 * - Failure retry (3 times / 10s interval); after retries are exhausted the batch is dropped and logged;
 * - Flushes the full buffer on close;
 * - 5s fetch timeout;
 * - read() unified transport skeleton (build request → fetch → parse and normalize).
 *
 * Subclasses only implement transport/dialect/parsing hooks:
 * - sendBatch: HTTP write of one batch of points (Line Protocol payload generated by serializeLineProtocol);
 * - buildReadRequest: QueryOptions → engine query request;
 * - parseReadResponse: engine raw response → DataPoint[] (result normalization).
 */
export abstract class InfluxBaseAdapter implements StorageAdapter {
  abstract readonly name: string;
  abstract readonly engineType: string;
  abstract readonly capabilities: AdapterCapabilities;
  protected abstract readonly logger: MinimalLogger;
  /** Error message prefix when read()'s HTTP fails (preserves each engine's original error semantics) */
  protected abstract readonly readErrorLabel: string;

  private buffer: DataPoint[] = [];
  private flushTimer: NodeJS.Timeout | null = null;
  private retryQueue: BufferedWrite[] = [];
  private retryTimer: NodeJS.Timeout | null = null;
  private isFlushing = false;
  private isClosed = false;

  // ──────────── write ────────────

  async write(points: DataPoint[]): Promise<WriteResult> {
    if (this.isClosed) {
      return {
        success: false,
        written: 0,
        failed: points.length,
        errors: [new Error('Adapter is closed')],
      };
    }

    for (const point of points) {
      this.buffer.push(point);
    }

    if (this.buffer.length >= BATCH_SIZE) {
      await this.flush();
    } else if (!this.flushTimer) {
      this.flushTimer = setTimeout(() => this.flush(), FLUSH_INTERVAL);
    }

    return { success: true, written: points.length, failed: 0 };
  }

  // ──────────── read (unified transport skeleton) ────────────

  async read(options: QueryOptions): Promise<DataPoint[]> {
    const request = await this.buildReadRequest(options);

    try {
      const response = await fetch(request.url, {
        method: 'POST',
        headers: request.headers,
        body: request.body,
        // CODE-05: add a 5s timeout to fetch
        signal: AbortSignal.timeout(FETCH_TIMEOUT_MS),
      });

      if (!response.ok) {
        const errorBody = await response.text().catch(() => 'unknown');
        throw new Error(`${this.readErrorLabel} failed (${response.status}): ${errorBody}`);
      }

      const rawText = await response.text();
      return this.parseReadResponse(rawText);
    } catch (error) {
      this.logger.error(`${this.readErrorLabel} error: ${(error as Error).message}`);
      throw error;
    }
  }

  // ──────────── Subclass hooks ────────────

  /** HTTP write of one batch of points (buffering/retry managed by the base class) */
  protected abstract sendBatch(points: DataPoint[]): Promise<void>;

  /** QueryOptions → engine query request (URL/headers/body); may be async (e.g. to resolve the project isolation unit) */
  protected abstract buildReadRequest(options: QueryOptions): Promise<EngineReadRequest>;

  /** Engine raw response text → unified DataPoint[] (result normalization) */
  protected abstract parseReadResponse(rawText: string): DataPoint[];

  // ──────────── Subclass hooks: delete / health (different semantics per engine, implemented by subclasses) ────────────

  abstract delete(options: { tagIds?: string[]; before?: Date }): Promise<number>;

  abstract health(): Promise<{ status: 'healthy' | 'degraded' | 'unhealthy'; details?: any }>;

  // ──────────── close ────────────

  async close(): Promise<void> {
    this.isClosed = true;
    this.flushAll();
    this.clearTimers();
    this.logger.log(`${this.constructor.name} closed`);
  }

  /** Number of points currently buffered for writing (reported by health()) */
  protected get pendingBufferCount(): number {
    return this.buffer.length;
  }

  // ──────────── Internal: Flush ────────────

  private async flush(): Promise<void> {
    if (this.isFlushing || this.buffer.length === 0) return;

    this.clearFlushTimer();

    this.isFlushing = true;
    const batch = this.buffer.splice(0, this.buffer.length);

    try {
      await this.sendBatch(batch);
      this.logger.debug(`Flushed ${batch.length} points to ${this.engineType}`);
    } catch (error) {
      this.logger.error(`Flush failed (${batch.length} points): ${(error as Error).message}`);
      this.enqueueRetry(batch);
    } finally {
      this.isFlushing = false;
    }
  }

  private flushAll(): void {
    this.clearFlushTimer();
    if (this.buffer.length > 0) {
      const batch = this.buffer.splice(0, this.buffer.length);
      this.sendBatch(batch).catch((err) => {
        this.logger.error(`Final flush failed: ${err.message}`);
      });
    }
  }

  // ──────────── Internal: Retry ────────────

  private enqueueRetry(points: DataPoint[]): void {
    this.retryQueue.push({ points, attempts: 0 });

    if (!this.retryTimer) {
      this.retryTimer = setInterval(() => this.processRetryQueue(), RETRY_INTERVAL);
    }
  }

  private async processRetryQueue(): Promise<void> {
    if (this.retryQueue.length === 0) {
      this.clearRetryTimer();
      return;
    }

    const remaining: BufferedWrite[] = [];

    for (const entry of this.retryQueue) {
      entry.attempts++;

      try {
        await this.sendBatch(entry.points);
        this.logger.log(
          `Retry succeeded on attempt ${entry.attempts}: ${entry.points.length} points`,
        );
      } catch (error) {
        if (entry.attempts < MAX_RETRIES) {
          remaining.push(entry);
          this.logger.warn(
            `Retry failed (attempt ${entry.attempts}/${MAX_RETRIES}): ${(error as Error).message}`,
          );
        } else {
          this.logger.error(
            `Retry exhausted after ${MAX_RETRIES} attempts, dropping ${entry.points.length} points`,
          );
        }
      }
    }

    this.retryQueue = remaining;
  }

  // ──────────── Internal: Timers ────────────

  private clearFlushTimer(): void {
    if (this.flushTimer) {
      clearTimeout(this.flushTimer);
      this.flushTimer = null;
    }
  }

  private clearRetryTimer(): void {
    if (this.retryTimer) {
      clearInterval(this.retryTimer);
      this.retryTimer = null;
    }
  }

  private clearTimers(): void {
    this.clearFlushTimer();
    this.clearRetryTimer();
  }
}
