/** Project before-delete event - notifies modules to release resources occupied by the project (e.g. DataSource) */
export interface ProjectBeforeDeleteEvent {
  projectId: string;
  /** Multi-tenant reserved (currently = projectId) */
  tenantId?: string;
  timestamp: number;
}

/** Project created event */
export interface ProjectCreatedEvent {
  projectId: string;
  /** Multi-tenant reserved (currently = projectId) */
  tenantId?: string;
  projectName: string;
}

/**
 * Project enabled-state change event
 *
 * Emitted by ProjectService.update() via EventBus when the enabled field changes;
 * the collection layer (DeviceCollectorBootstrap) subscribes to start/stop collection tasks dynamically.
 */
export interface ProjectEnabledEvent {
  projectId: string;
}

/** Project disabled event - the collection layer stops all the project's device collection tasks and unregisters state records */
export interface ProjectDisabledEvent {
  projectId: string;
}

/** Timer-config change event */
export interface TimerConfigChangedEvent {
  id: string;
  interval: number;
}

/** Template-sync completed event - notifies the collection side to batch-reload device tag tables */
export interface TemplateDevicesSyncedEvent {
  /** Template ID */
  templateId: string;
  /** List of affected device IDs */
  deviceIds: string[];
  /** Project ID */
  projectId: string;
  /** Protocol type */
  protocol: string;
  /** Change type */
  changeType: 'template_sync';
  /** Change statistics (optional) */
  summary?: {
    updated: number;
    added: number;
    removed: number;
  };
  timestamp: number;
}

export type EventPayload<T extends EventType> = EventPayloadMap[T];
