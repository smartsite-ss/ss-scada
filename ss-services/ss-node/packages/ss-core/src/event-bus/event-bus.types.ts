/**
 * Data-point change event
 *
 * Rework (P2-2): fields aligned with @ss-node/ss-collector-sdk's TagUpdatePayload,
 * pushed by PublishStep. timestamp is an ISO 8601 string (avoids Date serialization ambiguity).
 *
 * Backward compatibility: the original timestamp was a number; subscribers parsing it as a number must migrate to string.
 * Old subscribers reading timestamp now get an ISO string, convertible back via new Date(timestamp).
 */
export interface DataPointChangedEvent {
  tagId: string;
  deviceId: string;
  projectId: string;
  value: number | null;
  /** Display value (formatted), generated by FormatStep */
  displayValue?: string;
  quality: string;
  /** ISO 8601 string */
  timestamp: string;
  /** Errors produced in this Pipeline cycle (undefined when none) */
  errors?: Array<{ step: string; message: string; code?: string }>;
}

export interface DeviceStatusChangedEvent {
  deviceId: string;
  projectId: string;
  status: 'online' | 'offline' | 'connecting' | 'error' | 'degraded';
  previousStatus?: string;
  errorMessage?: string;
  timestamp: number;
}

export interface AlarmTriggeredEvent {
  alarmId: string;
  tagId: string;
  deviceId: string;
  projectId: string;
  level: 'critical' | 'high' | 'medium' | 'low';
  message: string;
  timestamp: number;
  value?: number;
  limit?: number;
}

export interface AlarmAcknowledgedEvent {
  alarmId: string;
  acknowledgedBy: string;
  acknowledgedAt: number;
}

/** Alarm-condition recovered event (emitted by AlarmCheckStep in the collection pipeline when a condition recovers).
 *  Phase 5 addition: AlarmRecoverySubscriber subscribes to this event to perform auto-recovery */
export interface AlarmNormalizedEvent {
  tagId: string;
  deviceId?: string;
  projectId: string;
  /** Collected value at recovery */
  value: number;
  timestamp: Date;
  message: string;
  /** The alarm-condition type that triggered this recovery (limit/deviation/rate/digital) */
  conditionType?: string;
}

/** Alarm auto-recovered event (emitted by AlarmRecoverySubscriber after performing auto-recovery).
 *  Phase 5 addition: frontend/notifications subscribe to this event to sense alarm loop closure */
export interface AlarmRecoveredEvent {
  recordId: string;
  tagId: string;
  deviceId?: string;
  projectId: string;
  /** Collected value at recovery */
  recoveredValue: string;
  recoveredAt: Date;
  ruleId?: string;
  /** Associated rule name (for frontend display) */
  ruleName?: string;
}

export interface ConfigChangedEvent {
  configType: 'tag' | 'device' | 'alarm' | 'system';
  targetId: string;
  changes: Record<string, any>;
  timestamp: number;
}

export interface ProcessingErrorEvent {
  step: string;
  error: Error;
  timestamp: number;
  context?: Record<string, any>;
}

export interface HealthEvent {
  checks: HealthCheck[];
  timestamp: number;
}

export interface HealthCheck {
  name: string;
  status: 'healthy' | 'unhealthy';
  error?: string;
  latency?: number;
  details?: Record<string, any>;
}

