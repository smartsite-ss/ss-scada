import type { PipelineValue } from './pipeline.types';

export interface DataPoint {
  tagId: string;
  deviceId: string;
  projectId: string;
  /** Device code (unique within the project; used for the Redis latest-value key hierarchy) */
  deviceCode?: string;
  /** Device name (used for display in the tree index) */
  deviceName?: string;
  value: PipelineValue;
  quality: string;
  timestamp: Date;
}

export const PERSIST_WRITER = 'PERSIST_WRITER';

/**
 * Tag-update event unified contract (P2-2)
 *
 * Standardizes the data format across the following scenarios:
 * - PersistStep builds a DataPoint to write to the persistence layer (Redis/SQLite/InfluxDB)
 * - PublishStep pushes the data_point_changed event via EventBus
 * - DataPushBridge forwards it to the WebSocket broadcast
 *
 * Field notes:
 * - value: raw value (already transformed, not formatted), keeps number/boolean/string semantics
 * - displayValue: string display value (already formatted, generated by FormatStep)
 * - timestamp: ISO 8601 string (avoids Date serialization ambiguity)
 * - errors: errors produced in this Pipeline cycle (undefined when no errors)
 */
export interface TagUpdatePayload {
  tagId: string;
  deviceId: string;
  projectId: string;
  value: PipelineValue;
  displayValue?: string;
  quality: string;
  timestamp: string;
  errors?: Array<{ step: string; message: string; code?: string }>;
  /** Active alarm (present only when this data triggered an alarm; omitted otherwise, zero overhead) */
  activeAlarms?: ActiveAlarmInfo[];
}

/** Active-alarm summary info */
export interface ActiveAlarmInfo {
  alarmId: string;
  level: string;
  condition: string;
  message: string;
}

/**
 * Writer priority
 * - critical: critical writers (e.g. Redis latest value, SQLite history), PersistStep awaits them synchronously
 * - best_effort: best-effort writers (e.g. InfluxDB, higher latency), PersistStep writes them fire-and-forget,
 *                not blocking the Pipeline main flow
 *
 * Defaults to critical, for backward compatibility.
 */
export type PersistWriterPriority = 'critical' | 'best_effort';

export interface IPersistWriter {
  readonly name: string;
  /**
   * Writer priority (optional, default critical).
   * Slow writers (e.g. InfluxDB) should declare best_effort to avoid dragging down the Pipeline cycle.
   */
  readonly priority?: PersistWriterPriority;
  /** Whether active (only active writers participate in the write buffer and metric counting) */
  isActive?: () => boolean;
  write(point: DataPoint): Promise<void>;
  writeBatch(points: DataPoint[]): Promise<void>;
  flush(): Promise<void>;
}
