/** Value type after transformation in the Pipeline - preserves the original data-type semantics (bool/string/number) */
export type PipelineValue = number | boolean | string | null;

export interface PipelineContext {
  tagId: string;
  deviceId: string;
  projectId: string;
  /** Device code (unique within the project; used for the Redis key hierarchy ss:latest:{projectId}:{deviceCode}) */
  deviceCode?: string;
  /** Tag name (for log diagnostics) */
  tagName?: string;
  /** Device name (for log diagnostics) */
  deviceName?: string;
  tagConfig?: any;
  deviceClient?: any;
  deviceType?: string;
  deviceConnection?: Record<string, any>;
  rawValue: any;
  rawTimestamp?: Date;
  transformedValue: PipelineValue;
  /** Formatted display value (string), generated by FormatStep from displayFormat */
  formattedValue?: string;
  quality: string;
  shouldPersist: boolean;
  shouldPublish: boolean;
  startTime: number;
  errors: Array<{ step: string; message: string; code?: string }>;
}

export interface PipelineStep {
  readonly name: string;
  readonly order: number;
  process(ctx: PipelineContext): Promise<PipelineContext>;
}

export interface StepMetrics {
  stepName: string;
  totalCalls: number;
  totalDurationMs: number;
  errorCount: number;
  lastCallAt: number | null;
  lastDurationMs: number | null;
}

export interface AlarmConditionType {
  type: 'limit' | 'deviation' | 'rate' | 'digital';
  severity: 'info' | 'warning' | 'critical';
  enabled: boolean;
}

export interface AlarmEvent {
  /** Pre-generated unique alarm ID (UUID), threaded through Pipeline and DB persistence */
  alarmId: string;
  tagId: string;
  deviceId: string;
  projectId: string;
  condition: AlarmConditionType;
  value: PipelineValue;
  timestamp: Date;
  message: string;
}

/**
 * Alarm-condition-recovered event (Phase 5 state-machine closed loop)
 *
 * Generated by AlarmCheckStep when it detects an alarm condition has recovered (isTriggered=false and the condition was previously active),
 * appended to PipelineContext.normalizedAlarms and emitted as the 'alarm_normalized' event by PublishStep.
 * AlarmRecoverySubscriber subscribes to this event and performs the auto-recovery.
 */
export interface NormalizedAlarmEvent {
  tagId: string;
  deviceId?: string;
  projectId: string;
  /** Collected value at recovery time */
  value: number;
  timestamp: Date;
  message: string;
  /** Alarm-condition type that triggered this recovery (limit/deviation/rate/digital) */
  conditionType?: string;
}
