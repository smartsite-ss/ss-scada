  if (props.forwardValue !== '' && rawStr === props.forwardValue) return 'svg_pool_fill';
  if (props.backwardValue !== '' && rawStr === props.backwardValue) return 'svg_pool_fill';
  if (props.stopValue !== '' && rawStr === props.stopValue) return 'svg_pool_fill';
