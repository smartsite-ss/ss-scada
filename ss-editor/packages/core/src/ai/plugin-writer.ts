/**
 * Plugin File Writer — P1-T05 plugin file output pipeline
 *
 * Responsibilities:
 *   1. Call PluginCodeGenerator.generateAll() to generate the TS skeleton
 *   2. Merge the LLM-returned code blocks into the skeleton (replacing the business logic parts)
 *   3. Return the full file tree (for AiAssistantPanel preview/download/writing)
 *
 * Merge strategy:
 *   - PluginClass file: keep the skeleton's imports/class declaration, replace the render method body
 *   - PropertySchema file: use the skeleton directly (the LLM does not generate the Schema)
 *   - index.ts: use the skeleton directly
 *   - locales: use the skeleton directly
 *
 * Usage:
 *   const writer = new PluginFileWriter();
 *   const fileTree = writer.buildFromLLMResponse(config, llmResponse);
 *   // fileTree → { 'PumpPlugin.ts': '...', 'index.ts': '...', ... }
 */

import { PluginCodeGenerator } from '@scada-editor/plugin-sdk';
import { RenderBackend } from '@scada-editor/plugin-sdk';
import { parseCodeBlocks } from './code-parser';
import type { PluginGenInput } from './plugin-generator-agent';

/** Final output file tree */
export type PluginFileTree = Record<string, string>;

/** Generation result (file tree + metadata) */
export interface PluginBuildResult {
  /** File tree path → content */
  files: PluginFileTree;
  /** Plugin type */
  type: string;
  /** Skeleton file path list */
  skeletonPaths: string[];
  /** LLM-generated file path list */
  llmPaths: string[];
}

/** PluginRenderBackend → RenderBackend enum mapping */
const RENDER_BACKEND_MAP: Record<string, RenderBackend> = {
  vue: RenderBackend.VUE_COMPONENT,
  canvas2d: RenderBackend.CANVAS_2D,
  'svg-dom': RenderBackend.SVG_DOM,
  'css-dom': RenderBackend.CSS_DOM,
  three3d: RenderBackend.THREE_3D,
};

/**
 * Convert PluginGenInput into the GenerateOptions required by PluginCodeGenerator
 */
function toCodeGenOptions(config: PluginGenInput) {
  return {
    type: config.type,
    label: config.label,
    category: config.category,
    renderBackend: RENDER_BACKEND_MAP[config.renderBackend] || RenderBackend.CANVAS_2D,
    schema: {
      fields: config.schema.fields.map((f) => ({
        name: f.name,
        type: f.type,
        label: f.label,
        defaultValue: f.defaultValue,
        required: f.required,
        min: f.min,
        max: f.max,
        group: f.group,
        options: f.options,
      })),
    },
  };
}

export class PluginFileWriter {
  /**
   * Build the final file tree from an LLM response
   *
   * @param config plugin config (inferred by PluginGeneratorAgent)
   * @param llmResponse the LLM's full Markdown response
   * @returns the merged file tree
   */
  buildFromLLMResponse(config: PluginGenInput, llmResponse: string): PluginBuildResult {
    // 1. Generate the TS skeleton
    const options = toCodeGenOptions(config);
    const skeleton = PluginCodeGenerator.generateAll(options);
    const skeletonPaths = Object.keys(skeleton);

    // 2. Parse code blocks from the LLM response
    const parsed = parseCodeBlocks(llmResponse);
    const llmPaths: string[] = [];

    // 3. Merge: LLM code replaces the corresponding skeleton files
    const merged: PluginFileTree = { ...skeleton };

    for (const file of parsed.files) {
      llmPaths.push(file.path);

      // Try to match a skeleton file
      const matchedKey = this._matchSkeletonPath(file.path, skeletonPaths);

      if (matchedKey) {
        // LLM-generated code replaces the skeleton
        merged[matchedKey] = file.code;
      } else {
        // New file (e.g. extra utility functions generated by the LLM)
        merged[file.path] = file.code;
      }
    }

    return {
      files: merged,
      type: config.type,
      skeletonPaths,
      llmPaths,
    };
  }

  /**
   * Build only the skeleton (no LLM involvement), for preview
   */
  buildSkeleton(config: PluginGenInput): PluginBuildResult {
    const options = toCodeGenOptions(config);
    const skeleton = PluginCodeGenerator.generateAll(options);

    return {
      files: skeleton,
      type: config.type,
      skeletonPaths: Object.keys(skeleton),
      llmPaths: [],
    };
  }

  /**
   * Try to match an LLM-returned file path to a skeleton file
   * Matches across multiple skeleton files
   * Matching logic: `ValvePlugin.ts` ↔ `src/ValvePlugin.ts` / `ValvePlugin.ts` / `valve-plugin.ts`
   */
  private _matchSkeletonPath(llmPath: string, skeletonPaths: string[]): string | null {
    const base = llmPath.replace(/^.*[/\\]/, '').toLowerCase();

    for (const sk of skeletonPaths) {
      const skBase = sk.replace(/^.*[/\\]/, '').toLowerCase();
      if (base === skBase) return sk;

      // Compare without extensions (e.g. ValvePlugin ↔ ValvePlugin.ts)
      const baseNoExt = base.replace(/\.[^.]+$/, '');
      const skNoExt = skBase.replace(/\.[^.]+$/, '');
      if (baseNoExt === skNoExt) return sk;
    }

    return null;
  }

  /**
   * Serialize the file tree into a downloadable JSON blob
   */
  static toDownloadBlob(files: PluginFileTree): Blob {
    const json = JSON.stringify(files, null, 2);
    return new Blob([json], { type: 'application/json' });
  }

  /**
   * Trigger a browser download
   */
  static downloadFiles(files: PluginFileTree, pluginType: string): void {
    const blob = this.toDownloadBlob(files);
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `${pluginType}-plugin.json`;
    a.click();
    URL.revokeObjectURL(url);
  }
}

/** Singleton */
export const pluginFileWriter = new PluginFileWriter();
